/**
 * Gets the data of a company if its recopilated
 * @param companyName The name of the company to find
 * @returns The company found or null if it doesn't exist
 * @author Oriol Plazas León
 * @since 15/08/2026
 */
export const findCompany = (companyName: string): Company | null => {
  return (
    COMPANIES.find(
      (c: Company) => c.name.toLowerCase().normalize() === companyName.toLowerCase().normalize(),
    ) || null
  )
}
